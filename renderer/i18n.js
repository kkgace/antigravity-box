// the en table overrides them when the display language is English.
let lang = 'zh-Hans';

export function setLanguage(pref) {
  if (pref === 'en' || pref === 'zh-Hans') lang = pref;
  else {
    const nav = String(navigator.language ?? '').toLowerCase();
    lang = nav.startsWith('en') ? 'en' : 'zh-Hans';
  }
  document.documentElement.lang = lang === 'en' ? 'en' : 'zh-CN';
}

export function getLanguage() {
  return lang;
}

